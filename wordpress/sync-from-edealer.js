/**
 * Copy the shared CSS, the script and the creatives from the eDealer build
 * into the plugin, so the two cannot drift.
 *
 * The stylesheet is identical in both. The script differs only in its
 * configuration block: eDealer hardcodes the paths, offers and addresses,
 * while the plugin reads them from window.GMI_CONFIG, which WordPress
 * prints. That one block is rewritten here rather than maintained twice.
 *
 *     node wordpress/sync-from-edealer.js            check only
 *     node wordpress/sync-from-edealer.js --write    apply
 *
 * It does NOT touch offers.php. The offer copy lives in two places on
 * purpose: edealer/offers.html is flat markup pasted into a CMS, and
 * offers.php is data. Change offers in both, or retire the build you are
 * not using.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'edealer');
const DST = path.join(ROOT, 'wordpress', 'golden-mile-incentives', 'assets');
const WRITE = process.argv.includes('--write');

const IMAGES = [
  'offer-durango.webp',
  'offer-compass.webp',
  'offer-wrangler-rubicon.webp',
  'offer-grand-cherokee.webp',
  'offer-cherokee-hybrid.webp',
];

let drift = 0;

function put(name, content, label) {
  const target = path.join(DST, name);
  const current = fs.existsSync(target) ? fs.readFileSync(target) : null;
  const next = Buffer.isBuffer(content) ? content : Buffer.from(content, 'utf8');

  if (current && current.equals(next)) {
    console.log('  same      ' + name + (label ? '  (' + label + ')' : ''));
    return;
  }
  drift++;
  if (WRITE) {
    fs.writeFileSync(target, next);
    console.log('  UPDATED   ' + name + (label ? '  (' + label + ')' : ''));
  } else {
    console.log('  DIFFERS   ' + name + (label ? '  (' + label + ')' : '') + '  — run with --write');
  }
}

/* ---------- stylesheet: copied verbatim ---------- */
put('gm-incentives.css', fs.readFileSync(path.join(SRC, 'gm-incentives.css')));

/* ---------- script: config block swapped for window.GMI_CONFIG ---------- */
function buildScript() {
  let s = fs.readFileSync(path.join(SRC, 'gm-incentives.js'), 'utf8');

  const iife = s.indexOf('(function () {');
  if (iife === -1) throw new Error('IIFE not found in edealer/gm-incentives.js');
  s = `/* Golden Mile incentives - WordPress plugin behaviour.

   GENERATED from edealer/gm-incentives.js by wordpress/sync-from-edealer.js.
   Do not edit this file: edit the eDealer one and re-run the script.

   The motion layer, the claim gate and the lead POST are identical. The
   only difference is configuration: the offer set, the two page URLs and
   the lead addresses arrive on window.GMI_CONFIG, printed by the plugin,
   instead of being hardcoded. Safe to load on both pages: each block
   no-ops if its elements are absent. */
` + s.slice(iife);

  const start = s.indexOf('  /* ----------------------------------------------------------------\n     CONFIG');
  const end = s.indexOf('  /* ---------- offers page: countdown ---------- */');
  if (start === -1 || end === -1) throw new Error('config block not found in edealer/gm-incentives.js');

  s = s.slice(0, start) + `  /* ----------------------------------------------------------------
     CONFIG

     Printed by the plugin - see gmi_enqueue() in
     golden-mile-incentives.php. Change any of it from WordPress with the
     'gmi_settings' and 'gmi_offers' filters; nothing here needs editing.

     OFFERS is keyed by the same slug the cards use in ?offer=<key>, and
     both come from offers.php, so they cannot disagree.

     Leads go to leadTo with leadCc copied, through FormSubmit, which needs
     a one-time activation click before anything is delivered. Once
     activated, swap leadTo for the hashed alias FormSubmit issues.
  ---------------------------------------------------------------- */
  var CFG = window.GMI_CONFIG || {};
  var OFFERS = CFG.offers || {};
  var OFFERS_URL = CFG.offersUrl || '/offers/';
  var LEAD_TO = CFG.leadTo || '';
  var LEAD_CC = CFG.leadCc || '';
  var PHONE = CFG.phone || '647-288-5337';
  var PHONE_HREF = CFG.phoneHref || '+16472885337';
  var MAIL_ENDPOINT = 'https://formsubmit.co/ajax/' + LEAD_TO;
  var EVENT_ENDS = CFG.eventEnds || '';

` + s.slice(end);

  // WordPress permalinks are real URLs, so eDealer's preview rewriting goes
  s = s.replace(/resolvePath\(OFFERS_PATH\)/g, 'OFFERS_URL');
  // and the countdown stays quiet when no end date is configured
  s = s.replace(
    "  var countdown = document.getElementById('gmi-countdown');\n  if (countdown) {",
    "  var countdown = document.getElementById('gmi-countdown');\n  if (countdown && EVENT_ENDS) {"
  );
  // the failure message uses the configured phone number
  s = s.replace(
    `        '<a href="tel:+16472885337">647-288-5337</a> or email ' +`,
    `        '<a href="tel:' + PHONE_HREF + '">' + PHONE + '</a> or email ' +`
  );

  const leftovers = ['PREVIEW_FILES', 'resolvePath', 'CLAIM_PATH', 'isPreview', 'github.io', 'ejay@', '2026-11-02T']
    .filter((t) => s.includes(t));
  if (leftovers.length) {
    throw new Error('eDealer-specific code left in the generated script: ' + leftovers.join(', '));
  }
  return s;
}

put('gm-incentives.js', buildScript(), 'generated');

/* ---------- creatives ---------- */
for (const img of IMAGES) {
  const from = path.join(ROOT, 'assets', img);
  if (!fs.existsSync(from)) {
    console.log('  MISSING   assets/' + img);
    drift++;
    continue;
  }
  put(img, fs.readFileSync(from));
}

console.log('');
if (!drift) {
  console.log('RESULT: plugin assets are in sync with the eDealer build');
} else if (WRITE) {
  console.log('RESULT: updated ' + drift + ' file(s)');
} else {
  console.log('RESULT: ' + drift + ' file(s) out of sync — re-run with --write');
  process.exitCode = 1;
}
